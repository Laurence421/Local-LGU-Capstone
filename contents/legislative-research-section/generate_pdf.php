<?php
// Include auth protection
require_once __DIR__ . '/../../auth.php';

// Include composer autoload for TCPDF
require_once __DIR__ . '/../../vendor/autoload.php';

// Check if this is a POST request with the correct action
if ($_SERVER['REQUEST_METHOD'] !== 'POST' || !isset($_POST['action'])) {
    http_response_code(400);
    die('Invalid request');
}

$action = $_POST['action'];

// Handle bulk PDF generation
if ($action === 'generate_bulk_pdf') {
    if (!isset($_POST['measures_data'])) {
        http_response_code(400);
        die('No measures data provided');
    }
    
    $measuresData = json_decode($_POST['measures_data'], true);
    if (!$measuresData || !is_array($measuresData)) {
        http_response_code(400);
        die('Invalid measures data format');
    }
    
    $dateFrom = $_POST['date_from'] ?? '';
    $dateTo = $_POST['date_to'] ?? '';
    
    try {
        // Create new PDF document
        $pdf = new TCPDF(PDF_PAGE_ORIENTATION, PDF_UNIT, PDF_PAGE_FORMAT, true, 'UTF-8', false);

        // Set document information
        $pdf->SetCreator('LGU Research System');
        $pdf->SetAuthor('Legislative Research Section');
        $pdf->SetTitle('Bulk Measures Report');
        $pdf->SetSubject('Legislative Measures Bulk Report');
        $pdf->SetKeywords('LGU, Legislative, Measures, Bulk Report');

        // Set default header data
        $pdf->SetHeaderData('', 0, 'LGU RESEARCH SYSTEM', 'Bulk Measures Report', array(17, 82, 114), array(17, 82, 114));
        $pdf->setFooterData(array(0, 64, 0), array(0, 64, 128));

        // Set header and footer fonts
        $pdf->setHeaderFont(Array(PDF_FONT_NAME_MAIN, '', PDF_FONT_SIZE_MAIN));
        $pdf->setFooterFont(Array(PDF_FONT_NAME_DATA, '', PDF_FONT_SIZE_DATA));

        // Set default monospaced font
        $pdf->SetDefaultMonospacedFont(PDF_FONT_MONOSPACED);

        // Set margins
        $pdf->SetMargins(PDF_MARGIN_LEFT, PDF_MARGIN_TOP, PDF_MARGIN_RIGHT);
        $pdf->SetHeaderMargin(PDF_MARGIN_HEADER);
        $pdf->SetFooterMargin(PDF_MARGIN_FOOTER);

        // Set auto page breaks
        $pdf->SetAutoPageBreak(TRUE, PDF_MARGIN_BOTTOM);

        // Set image scale factor
        $pdf->setImageScale(PDF_IMAGE_SCALE_RATIO);

        // Add cover page
        $pdf->AddPage();
        $pdf->SetFont('helvetica', '', 11);
        
        // Date range text
        $dateRangeText = 'All dates';
        if ($dateFrom && $dateTo) {
            $dateRangeText = $dateFrom . ' to ' . $dateTo;
        } elseif ($dateFrom) {
            $dateRangeText = 'From ' . $dateFrom;
        } elseif ($dateTo) {
            $dateRangeText = 'Until ' . $dateTo;
        }
        
        $coverHtml = '
        <style>
            body { font-family: "Times New Roman", serif; font-size: 12pt; line-height: 1.4; }
            .header-section { text-align: center; margin-bottom: 40px; margin-top: 100px; }
            .republic { font-size: 14pt; font-weight: normal; margin-bottom: 5px; }
            .council-name { font-size: 24pt; font-weight: bold; margin-bottom: 10px; }
            .report-title { font-size: 20pt; font-weight: bold; margin: 40px 0; color: #004a8b; }
            .info-section { margin: 40px 0; text-align: center; }
            .info-label { font-weight: bold; font-size: 14pt; margin-bottom: 5px; }
            .info-value { font-size: 14pt; margin-bottom: 20px; }
        </style>

        <div class="header-section">
            <div class="republic">Republic of the Philippines</div>
            <div class="council-name">LGU RESEARCH SYSTEM</div>
            <div class="report-title">BULK MEASURES REPORT</div>
        </div>

        <div class="info-section">
            <div class="info-label">Date Range:</div>
            <div class="info-value">' . $dateRangeText . '</div>
            
            <div class="info-label">Total Records:</div>
            <div class="info-value">' . count($measuresData) . ' measure(s)</div>
            
            <div class="info-label">Generated On:</div>
            <div class="info-value">' . date('F j, Y \a\t g:i A') . '</div>
            
            <div class="info-label">Generated By:</div>
            <div class="info-value">' . ($_SESSION['fullname'] ?? $_SESSION['username'] ?? 'System User') . '</div>
        </div>
        ';
        
        $pdf->writeHTML($coverHtml, true, false, true, false, '');
        
        // Add summary table page
        $pdf->AddPage();
        
        $summaryHtml = '
        <style>
            .summary-title { font-size: 16pt; font-weight: bold; margin-bottom: 20px; color: #004a8b; }
            .summary-table { width: 100%; border-collapse: collapse; }
            .summary-table th { background-color: #004a8b; color: white; padding: 8px; text-align: left; font-size: 10pt; }
            .summary-table td { padding: 6px; border-bottom: 1px solid #ddd; font-size: 9pt; }
            .summary-table tr:nth-child(even) { background-color: #f9f9f9; }
        </style>
        
        <div class="summary-title">Summary of Measures</div>
        
        <table class="summary-table">
            <thead>
                <tr>
                    <th style="width: 5%;">#</th>
                    <th style="width: 15%;">Date Created</th>
                    <th style="width: 50%;">Title</th>
                    <th style="width: 15%;">Type</th>
                    <th style="width: 15%;">Status</th>
                </tr>
            </thead>
            <tbody>';
        
        foreach ($measuresData as $index => $measure) {
            $title = htmlspecialchars_decode($measure['measure_title'] ?? 'N/A', ENT_QUOTES);
            $truncatedTitle = strlen($title) > 60 ? substr($title, 0, 60) . '...' : $title;
            
            $summaryHtml .= '
                <tr>
                    <td>' . ($index + 1) . '</td>
                    <td>' . htmlspecialchars($measure['date_created'] ?? 'N/A') . '</td>
                    <td>' . htmlspecialchars($truncatedTitle) . '</td>
                    <td>' . htmlspecialchars($measure['measure_type'] ?? 'N/A') . '</td>
                    <td>' . htmlspecialchars($measure['measure_status'] ?? 'N/A') . '</td>
                </tr>';
        }
        
        $summaryHtml .= '
            </tbody>
        </table>';
        
        $pdf->writeHTML($summaryHtml, true, false, true, false, '');
        
        // Add individual measure pages
        foreach ($measuresData as $index => $measureData) {
            $pdf->AddPage();
            
            $dateCreated = htmlspecialchars_decode($measureData['date_created'] ?? 'N/A', ENT_QUOTES);
            $measureType = htmlspecialchars_decode($measureData['measure_type'] ?? 'N/A', ENT_QUOTES);
            $measureTitle = htmlspecialchars_decode($measureData['measure_title'] ?? 'N/A', ENT_QUOTES);
            $introducers = htmlspecialchars_decode($measureData['introducers'] ?? 'N/A', ENT_QUOTES);
            $measureContent = htmlspecialchars_decode($measureData['measure_content'] ?? 'N/A', ENT_QUOTES);
            $datetimeSubmitted = htmlspecialchars_decode($measureData['datetime_submitted'] ?? 'N/A', ENT_QUOTES);
            $checkingRemarksPending = htmlspecialchars_decode($measureData['checking_remarks_pending'] ?? 'N/A', ENT_QUOTES);
            $checkingRemarksApproved = htmlspecialchars_decode($measureData['checking_remarks_approved'] ?? 'N/A', ENT_QUOTES);
            $checkingNotes = htmlspecialchars_decode($measureData['checking_notes'] ?? 'N/A', ENT_QUOTES);
            
            $measureHtml = '
            <style>
                .measure-number { font-size: 12pt; color: #666; margin-bottom: 10px; }
                .measure-type { text-align: center; font-size: 14pt; font-weight: bold; margin: 15px 0; }
                .measure-title { text-align: center; font-weight: bold; font-size: 12pt; margin: 15px 0; }
                .section-title { font-weight: bold; font-size: 11pt; margin: 15px 0 8px 0; color: #004a8b; }
                .content-box { padding: 10px; background-color: #f8f9fa; border: 1px solid #e9ecef; margin-bottom: 10px; font-size: 10pt; }
                .date-row { margin: 10px 0; }
                .date-label { font-weight: bold; display: inline; }
            </style>
            
            <div class="measure-number">Measure #' . ($index + 1) . ' of ' . count($measuresData) . '</div>
            
            <div class="measure-type">' . strtoupper($measureType) . '</div>
            <div class="measure-title">' . $measureTitle . '</div>
            
            <div class="section-title">Introducers:</div>
            <div class="content-box">' . $introducers . '</div>
            
            <div class="date-row">
                <span class="date-label">Date Created:</span> ' . $dateCreated . ' | 
                <span class="date-label">Submitted:</span> ' . $datetimeSubmitted . '
            </div>
            
            <div class="section-title">Checking Remarks (Pending):</div>
            <div class="content-box">' . $checkingRemarksPending . '</div>
            
            <div class="section-title">Checking Remarks (Approved):</div>
            <div class="content-box">' . $checkingRemarksApproved . '</div>
            
            <div class="section-title">Checking Notes:</div>
            <div class="content-box">' . nl2br($checkingNotes) . '</div>
            ';
            
            $pdf->writeHTML($measureHtml, true, false, true, false, '');
        }

        // Generate filename
        $dateStr = ($dateFrom && $dateTo) ? $dateFrom . '_to_' . $dateTo : date('Y-m-d');
        $filename = 'bulk_measures_report_' . $dateStr . '.pdf';

        // Clean output buffer
        if (ob_get_length()) {
            ob_end_clean();
        }

        // Output PDF
        $pdf->Output($filename, 'D');
        exit;

    } catch (Exception $e) {
        error_log('Bulk PDF Generation Error: ' . $e->getMessage());
        http_response_code(500);
        header('Content-Type: application/json');
        echo json_encode(['error' => 'Failed to generate bulk PDF: ' . $e->getMessage()]);
        exit;
    }
}

// Handle single PDF generation
if ($action !== 'generate_pdf') {
    http_response_code(400);
    die('Invalid action');
}

// Check if measure data is provided
if (!isset($_POST['measure_data'])) {
    http_response_code(400);
    die('No measure data provided');
}

// Decode the measure data
$measureData = json_decode($_POST['measure_data'], true);
if (!$measureData) {
    http_response_code(400);
    die('Invalid measure data format');
}

// Sanitize and prepare data
$dateCreated = htmlspecialchars_decode($measureData['date_created'] ?? 'N/A', ENT_QUOTES);
$measureType = htmlspecialchars_decode($measureData['measure_type'] ?? 'N/A', ENT_QUOTES);
$measureTitle = htmlspecialchars_decode($measureData['measure_title'] ?? 'N/A', ENT_QUOTES);
$introducers = htmlspecialchars_decode($measureData['introducers'] ?? 'N/A', ENT_QUOTES);
$measureContent = htmlspecialchars_decode($measureData['measure_content'] ?? 'N/A', ENT_QUOTES);
$datetimeSubmitted = htmlspecialchars_decode($measureData['datetime_submitted'] ?? 'N/A', ENT_QUOTES);
$checkingRemarksPending = htmlspecialchars_decode($measureData['checking_remarks_pending'] ?? 'N/A', ENT_QUOTES);
$checkingRemarksApproved = htmlspecialchars_decode($measureData['checking_remarks_approved'] ?? 'N/A', ENT_QUOTES);
$checkingNotes = htmlspecialchars_decode($measureData['checking_notes'] ?? 'N/A', ENT_QUOTES);
$measureId = $measureData['id'] ?? 'unknown';

try {
    // Create new PDF document
    $pdf = new TCPDF(PDF_PAGE_ORIENTATION, PDF_UNIT, PDF_PAGE_FORMAT, true, 'UTF-8', false);

    // Set document information
    $pdf->SetCreator('LGU Research System');
    $pdf->SetAuthor('Legislative Research Section');
    $pdf->SetTitle('Measure Document - ' . $measureType);
    $pdf->SetSubject('Legislative Measure Report');
    $pdf->SetKeywords('LGU, Legislative, Measure, ' . $measureType);

    // Set default header data
    $pdf->SetHeaderData('', 0, 'LGU RESEARCH SYSTEM', 'Legislative Measure Report', array(17, 82, 114), array(17, 82, 114));
    $pdf->setFooterData(array(0, 64, 0), array(0, 64, 128));

    // Set header and footer fonts
    $pdf->setHeaderFont(Array(PDF_FONT_NAME_MAIN, '', PDF_FONT_SIZE_MAIN));
    $pdf->setFooterFont(Array(PDF_FONT_NAME_DATA, '', PDF_FONT_SIZE_DATA));

    // Set default monospaced font
    $pdf->SetDefaultMonospacedFont(PDF_FONT_MONOSPACED);

    // Set margins
    $pdf->SetMargins(PDF_MARGIN_LEFT, PDF_MARGIN_TOP, PDF_MARGIN_RIGHT);
    $pdf->SetHeaderMargin(PDF_MARGIN_HEADER);
    $pdf->SetFooterMargin(PDF_MARGIN_FOOTER);

    // Set auto page breaks
    $pdf->SetAutoPageBreak(TRUE, PDF_MARGIN_BOTTOM);

    // Set image scale factor
    $pdf->setImageScale(PDF_IMAGE_SCALE_RATIO);

    // Add a page
    $pdf->AddPage();

    // Set font for content
    $pdf->SetFont('helvetica', '', 11);

    // Create the PDF content using only database columns
    $html = '
    <style>
        body { font-family: "Times New Roman", serif; font-size: 12pt; line-height: 1.4; }
        .header-section { text-align: center; margin-bottom: 40px; }
        .republic { font-size: 14pt; font-weight: normal; margin-bottom: 5px; }
        .council-name { font-size: 18pt; font-weight: bold; margin-bottom: 5px; }
        .city-name { font-size: 14pt; font-weight: normal; margin-bottom: 3px; }
        .measure-type { text-align: center; font-size: 16pt; font-weight: bold; margin: 30px 0; }
        .measure-title { text-align: center; font-weight: bold; font-size: 14pt; margin: 30px 0; text-transform: uppercase; }
        .introduced-section { margin: 30px 0; }
        .introduced-label { font-style: italic; margin-bottom: 10px; }
        .councilor-names { text-align: justify; line-height: 1.6; }
        .content-section { margin: 30px 0; text-align: justify; }
        .content-title { font-weight: bold; font-size: 13pt; margin-bottom: 15px; }
        .content-box { margin: 20px 0; padding: 15px; border: 1px solid #000; text-align: justify; line-height: 1.6; }
        .date-table { width: 100%; margin: 20px 0; border-collapse: collapse; }
        .date-table td { width: 50%; vertical-align: top; padding-right: 10px; }
        .date-label { font-weight: bold; margin-bottom: 5px; }
        .divider { border-bottom: 2px solid #000; margin: 20px 0; }
        .generation-info { margin-top: 30px; text-align: center; font-size: 10pt; color: #666; }
    </style>

    <div class="header-section">
        <div class="republic">Republic of the Philippines</div>
        <div class="council-name">LGU RESEARCH SYSTEM</div>
        <div class="city-name">Legislative Document</div>
    </div>

    <div class="measure-type">' . strtoupper($measureType) . '</div>

    <div class="measure-title">' . $measureTitle . '</div>

    <div class="divider"></div>

    <div class="introduced-section">
        <div class="introduced-label"><em>Introduced by:</em></div>
        <div class="councilor-names">' . $introducers . '</div>
    </div>

    <div class="divider"></div>

    <table class="date-table">
        <tr>
            <td>
                <div class="date-label">Date Created:</div>
                <div>' . $dateCreated . '</div>
            </td>
            <td>
                <div class="date-label">Date & Time Submitted:</div>
                <div>' . $datetimeSubmitted . '</div>
            </td>
        </tr>
    </table>

    <div style="page-break-before: always;"></div>

    <div class="content-section">
        <div class="content-title">MEASURE CONTENT:</div>
        <div class="content-box">' . nl2br($measureContent) . '</div>
    </div>
    
    <div style="page-break-before: always;"></div>
    
    <div style="margin-top: 30px;">
        <div style="font-weight: bold; font-size: 13pt; margin-bottom: 15px;">CHECKING REMARKS:</div>
        
        <div style="margin-bottom: 15px;">
            <div style="font-weight: bold; margin-bottom: 5px;">Checking Remarks in Pending Measures:</div>
            <div style="padding: 8px; background-color: #f8f9fa; border: 1px solid #e9ecef; border-radius: 4px;">' . $checkingRemarksPending . '</div>
        </div>
        
        <div style="margin-bottom: 15px;">
            <div style="font-weight: bold; margin-bottom: 5px;">Checking Remarks in Approved Measures:</div>
            <div style="padding: 8px; background-color: #f8f9fa; border: 1px solid #e9ecef; border-radius: 4px;">' . $checkingRemarksApproved . '</div>
        </div>
        
        <div style="margin-bottom: 15px;">
            <div style="font-weight: bold; margin-bottom: 5px;">Checking Notes:</div>
            <div style="padding: 8px; background-color: #f8f9fa; border: 1px solid #e9ecef; border-radius: 4px;">' . nl2br($checkingNotes) . '</div>
        </div>
        
        <div class="generation-info">
            Generated on: ' . date('F j, Y \a\t g:i A') . '<br>
            Generated by: ' . ($_SESSION['fullname'] ?? $_SESSION['username'] ?? 'System User') . '
        </div>
    </div>
    ';

    // Print content
    $pdf->writeHTML($html, true, false, true, false, '');

    // Generate filename
    $filename = 'measure_' . $measureId . '_' . date('Y-m-d_H-i-s') . '.pdf';

    // Clean output buffer
    if (ob_get_length()) {
        ob_end_clean();
    }

    // Output PDF
    $pdf->Output($filename, 'D'); // 'D' forces download

} catch (Exception $e) {
    // Log error
    error_log('PDF Generation Error: ' . $e->getMessage());
    
    // Return error response
    http_response_code(500);
    header('Content-Type: application/json');
    echo json_encode(['error' => 'Failed to generate PDF: ' . $e->getMessage()]);
}
