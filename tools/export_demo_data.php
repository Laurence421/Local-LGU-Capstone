<?php
/**
 * Export the DEMO database as the data file of the static GitHub Pages demo. Command line only.
 *
 *   php tools/export_demo_data.php > portfolio-demo/demo-data.js
 *
 * Refuses to run unless DEMO_MODE=true, so real records can never end up in the public snapshot.
 * tools/build_static_demo.js runs it for you.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require_once __DIR__ . '/../bootstrap.php';

if (!DEMO_MODE) {
    fwrite(STDERR, "Refusing to export: set DEMO_MODE=true (only the seeded demo database may be published).\n");
    exit(1);
}

$conn = db_connect();
if ($conn->connect_errno) {
    fwrite(STDERR, "Cannot connect to database: {$conn->connect_error}\n");
    exit(1);
}
$records = env('RECORDS_DB_NAME', env('DB_NAME'));

function rows($conn, $sql)
{
    $result = $conn->query($sql);
    if (!$result) {
        fwrite(STDERR, "Query failed: {$conn->error}\n");
        exit(1);
    }
    return $result->fetch_all(MYSQLI_ASSOC);
}

$data = [
    'exported_at' => date('c'),
    'measures' => rows($conn, "SELECT * FROM m9_similaritychecking ORDER BY m9_SC_ID"),
    'reviews' => rows($conn, "SELECT m9_SC_ID, review_stage, review_notes, reviewed_by, reviewed_at FROM m9_measure_reviews ORDER BY review_id"),
    'requests' => rows($conn, "SELECT id, user_id, username, email, measure_title, request_reason, status, request_date, updated_at, admin_notes FROM document_requests ORDER BY id"),
    // Never export password hashes
    'users' => rows($conn, "SELECT id, fullname, username, email, user_type, avatar_url, date_created, archived FROM users ORDER BY id"),
    'activity' => rows($conn, "SELECT id, user_id, username, action_type, action_description, created_at FROM audit_logs ORDER BY created_at DESC"),
    'docketing' => rows($conn, "SELECT * FROM `$records`.`m6_measuredocketing` ORDER BY m6_MD_ID"),
];

echo "/* Sample data for the static portfolio demo. Generated by tools/export_demo_data.php; every record is fictional. */\n";
echo 'window.DEMO_DATA = ' . json_encode($data, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT) . ";\n";
